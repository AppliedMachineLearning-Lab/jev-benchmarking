"""BabyAI-Text and TextWorld through BALROG's own code (Paglieri et al., ICLR 2025).

Nothing about the games or the prompt is reimplemented here. The environments come from BALROG's
`make_env` with BALROG's configuration (its pinned forks of minigrid and TextWorld, see
`scripts/setup_balrog_env.sh`), and the request is the conversation BALROG's naive agent would send: BALROG's
instruction prompt, its history of the last 16 observations and actions (`HistoryPromptBuilder`), and the
current observation. The episode loop follows `balrog.evaluator.Evaluator.run_episode`.

What Jev needs on top, and BALROG's free-text agents do not:
  * the options of the Choice question: BabyAI's six actions; for TextWorld, the commands TextWorld admits in
    the current state (BALROG accepts any text, so it does not list them). The naive agent's closing line
    ("You always have to output one of the above actions ...") is replaced by the Choice question.
  * the reference action: for BabyAI, the BabyAI bot of BALROG's minigrid fork, replanned at every step after
    the action actually taken; for TextWorld, the first command of the winning sequence TextWorld computes
    from the current state (`policy_commands`). Both know the whole level, including unseen objects.

Episodes: BabyAI-Text, BALROG's five tasks in turn with seeds 0..249 (one per episode); TextWorld, BALROG's three tasks with
seeds 0..24, which select each of the 25 games of a task once (BALROG picks game `seed % 25`). The games are
those BALROG uses (pregenerated by Lu et al., Intelligent Go-Explore), fetched from their repository at a
pinned commit. The episode reward is BALROG's progression (1 if solved; for TextWorld, score / max score
otherwise).
"""

