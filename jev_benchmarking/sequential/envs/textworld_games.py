"""TextWorld as in BALROG: the 75 pregenerated games, with TextWorld's own solver as reference.

BALROG (Paglieri et al., 2025) evaluates LLM agents on three TextWorld (Côté et al., 2018) game types with
games pregenerated by Lu et al. (Intelligent Go-Explore, MIT license), 25 per type:
  coin_collector    navigate a maze of rooms and pick up the coin,
  treasure_hunter   find an object, often behind locked doors or in locked containers,
  the_cooking_game  find the cookbook, gather and process the ingredients, prepare and eat the meal.
We use the same games, BALROG's step budget of 80, its instructions for each game type, and as options the
admissible commands TextWorld lists in each state. TextWorld 1.7 no longer plays the Glulx (.ulx) builds
of two game types, so those games are compiled from their game files to the Z-machine format with
TextWorld's bundled Inform 7 compiler; the cooking games ship a Z-machine build that is used as is.

The reference action is the first command of the winning sequence TextWorld computes from the current
state (`policy_commands`). The solver knows the whole game, including where unseen objects are and the
recipe before the cookbook is read, so on search steps its action is the best action under full
information. BALROG's progression metric (score / max score, 1 if won) is logged as the episode reward.
"""

import glob
import os
import re
import subprocess
from pathlib import Path

from jev_benchmarking.sequential.envs.base import ACTION, SUCCESS, Decision, EpisodeSpec, SequentialEnv, StepResult, _only_asked
from jev_benchmarking.tasks.base import choice, mc_criteria, noul, option_keys

GAMES_REPO = "https://github.com/conglu1997/intelligent-go-explore.git"
GAMES_COMMIT = "bcb4052e6de36a4389e666acd374832cfab1a042"
TASKS = ["coin_collector", "treasure_hunter", "the_cooking_game"]
STEP_BUDGET = 80  # BALROG's textworld max_episode_steps

# BALROG's instructions (balrog/environments/textworld/__init__.py, MIT license), without the command list
# (the options carry the commands) and without the step count, which the state gives as steps_left.
INSTRUCTIONS = {
    "coin_collector": (
        "You are an agent playing TextWorld, a text-based adventure game where you are in a randomly generated "
        "maze and must find the coin. You need to explore different rooms to find the target object. You can "
        "only go in a direction indicated with something like an exit or a door. Take the coin when you see it "
        "in the room."
    ),
    "treasure_hunter": (
        "You are an agent playing TextWorld, a text-based adventure game where you are in a randomly generated "
        "maze and must find a specific object. You need to explore different rooms to find the target object. "
        "The target object might be located in a closed or locked container. The adjective is useful for "
        "determining whether the key is matched with the lock (e.g. non-euclidean keycard is matched with "
        "non-euclidean safe). Make sure it is matched to unlock! The key required to unlock the door may be in "
        "another room or locked inside a container. Take the key whenever you can. After unlocking a locked "
        "door or container, it will remain closed. You will then need to open it."
    ),
    "the_cooking_game": (
        "You are an agent playing TextWorld, a text-based adventure game where you navigate through different "
        "rooms, interact with objects, and solve puzzles. Your goal is to first find the recipe, find and "
        "prepare food according to the recipe, and finally prepare and eat the meal. You can examine the "
        "cookbook to see the recipe when it is visible. The BBQ is for grilling things, the stove is for frying "
        "things, the oven is for roasting things. Cooking ingredients in the wrong way will lead to a failure of "
        "the game. Once you have got processed ingredients and the appropriate cooking tool ready, cook all of "
        "them according to the recipe. There are two conditions to correctly cook something (grill/fry/roast): "
        "a) the ingredient you want to cook is in your inventory and b) there is a suitable cooking tool in the "
        "room, and then use 'cook ... with ...' command. When you need to chop/slice/dice ingredients, you need "
        "to take the knife and the ingredient in your inventory and then 'slice/chop/dice ... with knife'. Make "
        "sure to first process the food (chop/slice/dice) before you try to cook them. When you have all the "
        "ingredients (that got processed or cooked according to the menu), you can 'prepare meal' in the kitchen "
        "and then 'eat meal' to win the game. The ingredients should EXACTLY match the color in the recipe, but "
        "if the recipe doesn't specify color, any color would be fine. You don't need to examine the "
        "container/supporter (e.g. toolbox) when it says something like \"there isn't a thing on it\"/\"has "
        "nothing on it\"."
    ),
}

ACTION_Q_TEXT = "Which command brings the player closest to completing the objective?"
SUCCESS_Q = noul("Will the player complete the objective before running out of steps?")


def games_dir() -> Path:
    return Path(os.environ.get("TEXTWORLD_GAMES", Path.home() / ".cache" / "jev-benchmarking" / "tw_games"))


def ensure_games() -> Path:
    """Fetch BALROG's games (pinned commit) and build Z-machine files where needed."""
    root = games_dir()
    src = root / "src"
    if not (src / "textworld" / "tw_games").is_dir():
        root.mkdir(parents=True, exist_ok=True)
        subprocess.run(["git", "clone", "-q", "--filter=blob:none", "--sparse", GAMES_REPO, str(src)], check=True)
        subprocess.run(["git", "-C", str(src), "sparse-checkout", "set", "textworld/tw_games"], check=True)
        subprocess.run(["git", "-C", str(src), "checkout", "-q", GAMES_COMMIT], check=True)
    return src / "textworld" / "tw_games"


def game_file(task: str, stem: str) -> str:
    """Path of a playable Z-machine build: shipped with the game, or compiled from its game file once."""
    tw_games = ensure_games()
    shipped = tw_games / task / f"{stem}.z8"
    if shipped.exists():
        return str(shipped)
    out = games_dir() / "z8" / task / f"{stem}.z8"
    if not out.exists():
        import textworld
        from textworld.generator import compile_game

        out.parent.mkdir(parents=True, exist_ok=True)
        options = textworld.GameOptions()
        options.path, options.file_ext, options.force_recompile = str(out), ".z8", True
        compile_game(textworld.Game.load(str(tw_games / task / f"{stem}.json")), options)
    return str(out)


class TextWorldGames(SequentialEnv):
    name = "textworld"
    description = "TextWorld, BALROG's 75 games (coin collector, treasure hunter, cooking); TextWorld solver reference."
    history_window = None  # full history

    def __init__(self, ask_success: bool = False):
        from jev_benchmarking.sequential.envs import alfworld  # noqa: F401  (TextWorld fix for Python 3.13)

        self.ask_success = ask_success
        self.max_steps = STEP_BUDGET
        self.env = None

    def episodes(self, split: str = "eval", limit: int | None = None) -> list[EpisodeSpec]:
        """All 75 games, interleaved by type so that any prefix (`--limit`) covers all three."""
        tw_games = ensure_games()
        per_task = {t: sorted(Path(p).stem for p in glob.glob(str(tw_games / t / "*.json"))) for t in TASKS}
        out = []
        for i in range(max(len(v) for v in per_task.values())):
            for t in TASKS:
                if i < len(per_task[t]):
                    out.append(EpisodeSpec(f"{t}/{per_task[t][i]}", t, {"task": t, "stem": per_task[t][i]}))
        return out[:limit] if limit is not None else out

    def reset(self, spec: EpisodeSpec) -> None:
        import textworld

        if self.env is not None:
            self.env.close()
        infos = textworld.EnvInfos(objective=True, description=True, inventory=True, admissible_commands=True,
                                   policy_commands=True, won=True, lost=True, score=True, max_score=True)
        self.env = textworld.start(game_file(spec.payload["task"], spec.payload["stem"]), request_infos=infos)
        self.gs = self.env.reset()
        self.task = spec.payload["task"]
        self.first_observation = self._strip(self.gs.feedback)
        self.history: list[dict] = []
        self.t = 0
        self.result: StepResult | None = None

    @staticmethod
    def _strip(text: str) -> str:
        """Game text without the ASCII-art title banner and the trailing prompt and status line."""
        lines = (text or "").split("\n")
        banner = [k for k, ln in enumerate(lines) if "$$" in ln]
        if banner:
            lines = lines[banner[-1] + 1:]
        for k, ln in enumerate(lines):
            if ln.startswith(">"):
                lines = lines[:k]
                break
        return re.sub(r"\n{3,}", "\n\n", "\n".join(lines)).strip()

    def state(self) -> dict:
        hist = self.history if self.history_window is None else self.history[-self.history_window:]
        return {
            "instructions": INSTRUCTIONS[self.task],
            "objective": self.gs.objective.strip(),
            "first_observation": self.first_observation,
            "current_room": (self.gs.description or "").strip(),
            "inventory": (self.gs.inventory or "").strip(),
            "history": list(hist),
            "steps_taken": self.t,
            "steps_left": self.max_steps - self.t,
        }

    def decision(self) -> Decision | None:
        if self.result is not None or self.gs.done:
            return None
        commands = list(self.gs.admissible_commands)
        policy = list(self.gs.policy_commands or [])
        oracle = {"expert": policy[0]} if policy and policy[0] in commands else {}
        oracle["solver_steps_left"] = len(policy)
        actions = dict(zip(option_keys(len(commands)), commands))
        q = choice(ACTION_Q_TEXT, mc_criteria(commands))
        questions = {ACTION: q, SUCCESS: SUCCESS_Q} if self.ask_success else {ACTION: q}
        return Decision(self.state(), questions, actions, oracle)

    def step(self, action: str) -> StepResult:
        self.gs, _, done = self.env.step(action)
        self.t += 1
        feedback = self._strip(self.gs.feedback)
        self.history.append({"command": action, "feedback": feedback})
        if done or self.gs.won or self.gs.lost:
            won = bool(self.gs.won)
            progress = 1.0 if won else (self.gs.score / self.gs.max_score if self.gs.max_score else 0.0)
            self.result = StepResult(True, won, float(progress), feedback)
            return self.result
        return StepResult(False, feedback=feedback)

    def outcome(self) -> StepResult:
        if self.result is not None:
            return self.result
        progress = self.gs.score / self.gs.max_score if self.gs.max_score else 0.0
        return StepResult(False, False, float(progress), "No steps left.")

    def close(self) -> None:
        if self.env is not None:
            self.env.close()
            self.env = None


def random_policy(state, questions):
    from jev_benchmarking.sequential.backends import choice_answer

    opts = list(questions[ACTION]["criteria"])
    return _only_asked(questions, {ACTION: choice_answer({c: 1 / len(opts) for c in opts})})


SCRIPTED = {"random": random_policy}
